#!/usr/bin/env python3
"""The pinned search with the free set F = the pairs with x divisible by 3 (--free ap3, when 3 divides n) or not divisible by 3 (--free non3, when it does
not: the class x = 0 mod 3 is then nearly fixed).  The fixed signs: class sums mod 3^L chosen so that the congruence residual lies in the subgroup S that
class-preserving swaps generate, annealing over swaps to bring F's target near its center, then a meet in the middle over swaps to cancel the residual in S."""
import sys, time, math, json, os, ctypes, argparse
from math import log2
import numpy as np
import mpmath as mp
from fpylll import IntegerMatrix, LLL
from pinned_problem import Problem, Congruence, default_profiles, echelon_rows, int_adj, exact_order, sequence, hexcode
from pinned_lattice import split_embedded, bound_fn
core = ctypes.CDLL(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'libpinned_anneal.so'))
core.anneal.restype = ctypes.c_double
core.mitm.restype = ctypes.c_longlong
dp = ctypes.POINTER(ctypes.c_double); ip = ctypes.POINTER(ctypes.c_int); i8p = ctypes.POINTER(ctypes.c_int8); i64p = ctypes.POINTER(ctypes.c_int64)


def whitened(P, xs, cols):
    """L^-1 c for each x, as rows of a C-ordered array: |y|^2 for y = L^-1 tau is the penalty perp2 = tau' Sigma_F^-1 tau."""
    Gm = P.Linv * mp.matrix([cols[x] for x in xs]).T
    G = np.ascontiguousarray(np.array([[float(Gm[i, j]) for j in range(len(xs))] for i in range(P.rho)]).T)
    assert G.flags.c_contiguous
    return G


class FixedSigns:
    def __init__(self, P, L, seed, log=print):
        self.P, self.L = P, L
        self.rng = np.random.default_rng(seed)
        self.Q3 = 3 ** L
        t0 = time.time()
        self.C = Congruence(P)
        self.cols = {x: P.vis_col(x) for x in P.Fx}
        self.G = whitened(P, P.Fx, self.cols)
        v = P.Linv * mp.matrix(P.vis_target())
        self.y0 = np.array([float(v[i]) for i in range(P.rho)])
        tot = [sum(self.cols[x][j] for x in P.Fx) + P.Sum[j] for j in range(P.rho)]
        tv = P.vis_target()
        assert all((t + w) % 2 == 0 for t, w in zip(tv, tot)), 'parity of totals on the visible rows'
        self.v0 = [(t + w) // 2 for t, w in zip(tv, tot)]
        self.C.split([self.cols[x] for x in P.Fx], self.v0)
        self.mods = self.C.moduli()
        self.nr = len(self.mods)
        self.psi = np.array([self.C.apply(self.cols[x]) for x in P.Fx], dtype=np.int64)
        self.psi0 = self.C.apply(self.v0)
        ids, chi, orb = {}, [], []
        for x in P.Fx:
            c, d = x % self.Q3, (-x) % self.Q3
            orb.append(ids.setdefault(min(c, d), len(ids)))
            chi.append(1 if (c <= d or P.s == 1) else -1)
        self.orb = np.array(orb, dtype=np.int32); self.chi = np.array(chi, dtype=np.int8); self.norb = len(ids)
        self.count = np.bincount(self.orb, minlength=self.norb)
        self.sumchi = np.zeros(self.norb, dtype=np.int64)
        for j in range(len(P.Fx)): self.sumchi[self.orb[j]] += self.chi[j]
        self.quotient()
        self.setup_class_lattice()
        log(f'FixedSigns: congruence rows {[(p, e - g) for p, _, e, g in self.C.rows]} bits {self.C.bits:.1f}; class-determined {self.resolved_bits:.1f} bits; swaps must cancel {self.left_bits:.1f} bits; orbits {self.norb}; setup {time.time()-t0:.1f}s')

    def quotient(self):
        """S = the subgroup of the congruence group generated by orientation-corrected differences inside orbits; rows phi of the quotient by S, which only class sums can move."""
        n = self.nr
        rows, ref = [], {}
        for j in range(len(self.orb)):
            o, ch = int(self.orb[j]), int(self.chi[j])
            w = [ch * int(v) for v in self.psi[j]]
            if o in ref: rows.append([(a - b) % m for a, b, m in zip(w, ref[o], self.mods)])
            else: ref[o] = w
        self.ref = ref
        M = IntegerMatrix.from_matrix(rows + [[self.mods[i] if i == k else 0 for i in range(n)] for k in range(n)])
        LLL.reduction(M, delta=0.99)
        B = [list(M[i]) for i in range(M.nrows) if any(M[i])]
        assert len(B) == n
        det, adj = int_adj(B)
        self.phi = []
        for p in sorted({p for p, _, _, _ in self.C.rows}):
            self.phi += [(vec, p ** e) for vec, e in echelon_rows(adj, det, p, n)]
        self.resolved_bits = sum(log2(mod) for _, mod in self.phi)
        self.left_bits = self.C.bits - self.resolved_bits

    def setup_class_lattice(self):
        """Solutions u (u_c = sum over orbit c of y_p chi_p) of the class-determined congruences and of the exact rows seen only by Fx."""
        rows, n, P, N = self.phi, self.norb, self.P, 2 ** 70
        self.phival, self.phit = [], []
        for vec, mod in rows:
            self.phival.append([sum(a * b for a, b in zip(vec, self.ref[c])) % mod for c in range(n)])
            self.phit.append(sum(a * b for a, b in zip(vec, self.psi0)) % mod)
        self.hrows = []
        for p in P.hard:
            h, seen = [0] * n, [False] * n
            for j, x in enumerate(P.Fx):
                w, o = p['row'].get(x, 0) * int(self.chi[j]), int(self.orb[j])
                if seen[o]: assert h[o] == w, 'hard row not constant on a class orbit: use a higher class level'
                h[o], seen[o] = w, True
            rhs = p['target'] + sum(h[c] * int(self.sumchi[c]) for c in range(n))
            assert rhs % 2 == 0, 'parity of a hard row'
            self.hrows.append((h, rhs // 2))
        M = IntegerMatrix(n + 1 + len(rows), n + 1 + len(rows) + len(self.hrows))
        for c in range(n):
            M[c, c] = 1
            for k in range(len(rows)): M[c, n + 1 + k] = N * self.phival[k][c]
            for k, (h, rhs) in enumerate(self.hrows): M[c, n + 1 + len(rows) + k] = N * h[c]
        M[n, n] = 1
        for k, (vec, mod) in enumerate(rows):
            M[n, n + 1 + k] = -N * self.phit[k]
            M[n + 1 + k, n + 1 + k] = N * mod
        for k, (h, rhs) in enumerate(self.hrows): M[n, n + 1 + len(rows) + k] = -N * rhs
        LLL.reduction(M, delta=0.99)
        zero = [list(M[i]) for i in range(M.nrows) if not any(list(M[i])[n + 1:])]
        hom, p = split_embedded(zero, n)
        assert p is not None, 'class equations unsolvable'
        self.cbasis = np.array([v[:n] for v in hom if any(v[:n])], dtype=np.int64)
        self.cpart = np.array(p[:n], dtype=np.int64)

    def class_targets(self, noise):
        """Orbit sums e_c near the orbits' centers meeting the class equations, or None if out of capacity.  noise > 0 varies them: at some lengths one fixed
        choice leaves a residual the swaps cannot reach with few moves (576:12)."""
        n = self.norb
        center = self.sumchi / 2.0 + self.rng.normal(0, noise, size=n) * np.sqrt(self.count) / 2.0
        if self.hrows:                                   # spread each exact row's demand over its orbits, in proportion to their sizes
            Hm = np.array([h for h, _ in self.hrows], dtype=np.float64)
            rhs = np.array([r for _, r in self.hrows], dtype=np.float64)
            W = np.diag(self.count.astype(np.float64))
            center = center + W @ Hm.T @ np.linalg.lstsq(Hm @ W @ Hm.T, rhs - Hm @ center, rcond=None)[0]
        if len(self.cbasis):
            coef = np.linalg.lstsq(self.cbasis.astype(np.float64).T, center - self.cpart, rcond=None)[0]
            u = self.cpart + np.round(coef).astype(np.int64) @ self.cbasis
        else:
            u = self.cpart.copy()
        pos = (self.count + self.sumchi) // 2; neg = self.count - pos
        def cost(w):
            over = np.maximum(w - pos, 0) + np.maximum(-neg - w, 0)
            return ((w - center) ** 2).sum() + 1000.0 * (over ** 2).sum()
        improved = True
        while improved:
            improved = False
            for v in self.cbasis:
                for sgn in (1, -1):
                    if cost(u + sgn * v) < cost(u) - 1e-9:
                        u = u + sgn * v; improved = True
        if np.any(u > pos) or np.any(u < -neg): return None
        for k, (vec, mod) in enumerate(self.phi):
            assert sum(self.phival[k][c] * int(u[c]) for c in range(n)) % mod == self.phit[k]
        for h, rhs in self.hrows:
            assert sum(a * int(b) for a, b in zip(h, u)) == rhs
        return (2 * u - self.sumchi).astype(np.int32)

    def anneal(self, e, flips, swaps, T0=0.6, T1=0.3, W=2.0):
        n, rho = self.G.shape
        a = self.rng.choice([-1, 1], size=n).astype(np.int8)
        y = self.y0 - a.astype(np.float64) @ self.G
        l1 = core.anneal(ctypes.c_int(n), ctypes.c_int(rho), self.G.ctypes.data_as(dp), a.ctypes.data_as(i8p), y.ctypes.data_as(dp),
                         self.orb.ctypes.data_as(ip), self.chi.ctypes.data_as(i8p), ctypes.c_int(self.norb), e.ctypes.data_as(ip),
                         ctypes.c_longlong(flips), ctypes.c_longlong(swaps), ctypes.c_double(T0), ctypes.c_double(T1), ctypes.c_double(W),
                         ctypes.c_ulonglong(int(self.rng.integers(1 << 62))))
        ycheck = self.y0 - a.astype(np.float64) @ self.G
        assert np.abs(ycheck - y).max() < 1e-5, np.abs(ycheck - y).max()
        return a, ycheck, l1

    def residual(self, a):
        yy = (a.astype(np.int64) + 1) // 2
        return np.array([(int(self.psi0[i]) - int(yy @ self.psi[:, i])) % self.mods[i] for i in range(self.nr)], dtype=np.int64)

    def mitm(self, a, y, t1, t2, cap, maxdn, maxout=4096):
        """Sets of t1 + t2 swaps, at most one per orbit, that cancel the residual, least perp2 first: [(perp2, flips)], and how many there were."""
        n, rho = self.G.shape
        r = self.residual(a)
        for k, (vec, mod) in enumerate(self.phi):
            assert sum(int(u) * int(v) for u, v in zip(vec, r)) % mod == 0, 'the residual is not in the swap subgroup'
        order = self.rng.permutation(self.norb).astype(np.int32)
        mods = np.array(self.mods, dtype=np.int64)
        out = np.zeros((maxout, 2 * (t1 + t2)), dtype=np.int32)
        sizes = np.zeros(2, dtype=np.int64)
        y = np.ascontiguousarray(y).astype(np.float64)
        cnt = core.mitm(ctypes.c_int(n), ctypes.c_int(self.nr), a.ctypes.data_as(i8p), self.orb.ctypes.data_as(ip), self.chi.ctypes.data_as(i8p),
                        ctypes.c_int(self.norb), self.psi.ctypes.data_as(i64p), mods.ctypes.data_as(i64p), r.ctypes.data_as(i64p),
                        ctypes.c_int(t1), ctypes.c_int(t2), order.ctypes.data_as(ip), ctypes.c_int(self.norb // 2), ctypes.c_longlong(cap),
                        self.G.ctypes.data_as(dp), ctypes.c_int(rho), y.ctypes.data_as(dp), ctypes.c_double(maxdn), ctypes.c_longlong(maxout),
                        out.ctypes.data_as(ip), ctypes.c_ulonglong(int(self.rng.integers(1 << 62))), sizes.ctypes.data_as(ctypes.POINTER(ctypes.c_longlong)))
        sgn = a.astype(np.float64)
        res = []
        for i in range(min(cnt, maxout)):
            fl = out[i]
            yn = y + (2 * sgn[fl][:, None] * self.G[fl]).sum(axis=0)
            res.append((float(yn @ yn), fl.copy()))
        res.sort(key=lambda t: t[0])
        return res, cnt

    def assemble(self, a, flips):
        P = self.P
        b = a.astype(np.int64).copy()
        for p in flips: b[p] = -b[p]
        dct = {x: int(v) for x, v in zip(P.Fx, b)}
        tau = list(P.vis_target())
        for x, v in dct.items(): tau = [t - v * w for t, w in zip(tau, self.cols[x])]
        for p in P.hard:
            assert sum(v * p['row'].get(x, 0) for x, v in dct.items()) == p['target'], 'hard row of the profile'
        return tau, dct


def search(a, log):
    n, m = a.n, a.m
    s = 1 if m % 2 == 0 else -1
    pf = default_profiles(n, m, [int(q) for q in a.qs.split(',')], log=log)
    F = [x for x in range(1, n, 2) if (x % 3 == 0) == (a.free == 'ap3')]
    P = Problem(n, m, F, pf, log=log)
    A = FixedSigns(P, a.L, a.seed, log=log)
    t0 = time.time(); rounds = cvps = nodes_all = 0; found = []
    while time.time() - t0 < a.tlimit and not (found and a.stop):
        rounds += 1
        e = None
        while e is None: e = A.class_targets(a.noise)
        x, y, l1 = A.anneal(e, int(a.flips), int(a.swaps))
        if l1 > 0: continue
        res, cnt = A.mitm(x, y, a.t1, a.t2, int(a.cap), a.maxdn)
        for Q, flips in res[:a.topk]:
            if Q > a.qgate: break
            tau, dct = A.assemble(x, flips)
            a1 = P.coset_base(tau)
            assert a1 is not None, 'not in the coset'
            sols, nodes, R2, ns = P.I.cvp(P.I.babai(a1), bound_fn=bound_fn(a.c, a.floor), max_nodes=int(a.maxnodes), maxsol=1000)
            cvps += 1; nodes_all += nodes
            perp2 = P.I.f - 4 * R2
            assert abs(perp2 - Q) < 1e-3, (perp2, Q)
            if nodes > 1000 or ns: log(f'  round {rounds}: perp2={perp2:.2f} log2E={P.log2Eceil - perp2 / 2 / math.log(2):.1f} nodes={nodes:.3g} sols={ns}')
            for row in sols:
                b = dict(dct)
                b.update({x_: int(v) for x_, v in zip(P.F, row)})
                fseq = sequence(n, s, b)
                o = exact_order(fseq)
                assert o >= m, o
                found.append(dict(n=n, m=m, order=o, code=hexcode(fseq, n), seed=a.seed, t=time.time() - t0, perp2=perp2))
                log(f'  WITNESS n={n} order={o} code={found[-1]["code"]}')
    log(f'done: rounds {rounds} CVPs {cvps} nodes {nodes_all:.3g} witnesses {len(found)} time {time.time()-t0:.0f}s')
    return found


def parser():
    ap = argparse.ArgumentParser()
    ap.add_argument('n', type=int); ap.add_argument('m', type=int); ap.add_argument('qs')
    ap.add_argument('--free', default='ap3', choices=('ap3', 'non3')); ap.add_argument('--L', type=int, default=4); ap.add_argument('--seed', type=int, default=1)
    ap.add_argument('--noise', type=float, default=0.0); ap.add_argument('--flips', type=float, default=4e5); ap.add_argument('--swaps', type=float, default=1e7)
    ap.add_argument('--t1', type=int, default=3); ap.add_argument('--t2', type=int, default=3); ap.add_argument('--cap', type=float, default=3e6); ap.add_argument('--maxdn', type=float, default=1.5)
    ap.add_argument('--topk', type=int, default=64); ap.add_argument('--qgate', type=float, default=1e9)
    ap.add_argument('--c', type=float, default=0.0); ap.add_argument('--floor', type=float, default=1.0); ap.add_argument('--maxnodes', type=float, default=1e9)
    ap.add_argument('--tlimit', type=float, default=3600); ap.add_argument('--stop', type=int, default=1); ap.add_argument('--out', default=None)
    return ap


if __name__ == '__main__':
    a = parser().parse_args()
    def log(*x): print(time.strftime('%H:%M:%S'), *x, flush=True)
    found = search(a, log)
    if a.out:
        with open(a.out, 'a') as fh:
            for w in found: fh.write(json.dumps(w) + '\n')
